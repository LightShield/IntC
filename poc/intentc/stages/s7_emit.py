"""Stage 7: Emission (paper Section 3.6 step 6). Writes the selected program as
reviewable source, with the proofs and measurements that justify it in a header.
If no candidate won, the baseline is emitted unchanged (conventional compilation)."""

from __future__ import annotations

from pathlib import Path

from intentc.pipeline.context import Context


def render(ctx: Context) -> str:
    c = ctx.winner
    lines = ["/* ===== generated by intentc =====", f" * contract: {ctx.contract.name}"]
    if ctx.pool:
        lines.append(f" * admitted: {len(ctx.pool)} candidate(s)")
        for p in ctx.pool:
            meas = f" measured={p.measured:.3f}" if p.measured is not None else ""
            if getattr(p, "measured_stats", None) is not None:
                st = p.measured_stats
                meas = f" measured={st.median:.3f}±{st.stdev:.3f} [{st.min:.3f},{st.max:.3f}]"
            lines.append(f" *   {p.name} params={p.params}{meas}")
    failed = [s for s in ctx.steps if not s.ok]
    if c is None:
        lines.append(" * result: baseline kept unchanged")
        if failed:
            lines.append(f" * cause: {failed[0].stage}: {failed[0].details}")
        elif ctx.baseline_measured is not None:
            lines.append(f" * cause: no admitted candidate measured faster than baseline {ctx.baseline_measured:.3f}")
        lines += [" */", ""]
        return "\n".join(lines) + ctx.baseline_code
    lines.append(f" * candidate: {c.name}")
    lines.append(f" * parameters: {c.params} (baseline {ctx.baseline_params})")
    for h, r in zip(ctx.contract.harnesses, c.proofs):
        lines.append(f" * proved by CBMC 6.11.0: {h.file.name} entry={h.entry} unwind={h.unwind} "
                     f"defines={h.defines} in {r.seconds:.1f}s")
    if c.measured is not None:
        n = ctx.contract.objective.trials
        if getattr(c, "measured_stats", None) is not None and getattr(ctx, "baseline_stats", None) is not None:
            w, b = c.measured_stats, ctx.baseline_stats
            lines.append(
                f" * measured: {w.median:.3f} ± {w.stdev:.3f} [{w.min:.3f},{w.max:.3f}] vs baseline "
                f"{b.median:.3f} ± {b.stdev:.3f} [{b.min:.3f},{b.max:.3f}] "
                f"({ctx.contract.objective.metric}, median ± sample stdev of {n} trials)"
            )
        else:
            lines.append(f" * measured: {c.measured:.3f} vs baseline {ctx.baseline_measured:.3f} "
                         f"({ctx.contract.objective.metric}, median of {n})")
    elif ctx.contract.objective is None:
        lines.append(" * selection: no objective; emitted first admitted candidate")
    lines += [" */", ""]
    return "\n".join(lines) + c.code


def emit(ctx: Context) -> tuple[bool, str]:
    """Write the result to ctx.output (if set)."""
    text = render(ctx)
    if ctx.output is not None:
        ctx.output.parent.mkdir(parents=True, exist_ok=True)
        ctx.output.write_text(text, encoding="utf-8")
        out = Path(ctx.output)
        try:
            shown = out.resolve().relative_to(Path.cwd().resolve()).as_posix()
        except ValueError:
            shown = out.name
        return True, f"wrote {shown}"
    return True, "rendered (no output path)"
