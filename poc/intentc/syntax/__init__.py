"""C as text: tree-sitter parse, span edits, #define parameters, rewrite sketches.

Candidates stay C source. There is no CFG/SSA intermediate. tree-sitter is
the parser, not the module's job.
"""

from __future__ import annotations

from collections.abc import Iterator
from dataclasses import dataclass

import tree_sitter_cpp as tscpp
from tree_sitter import Language, Node, Parser, Tree

_LANG = Language(tscpp.language())


@dataclass(frozen=True)
class Sketch:
    """A rewrite output: source plus side constraints on holes. Not yet a result."""

    code: str
    side_constraints: tuple[str, ...]
    applied: tuple[str, ...]
    extra_params: tuple[str, ...] = ()


def parse(code: str) -> tuple[Tree, bytes]:
    data = code.encode("utf-8")
    tree = Parser(_LANG).parse(data)
    if tree.root_node.has_error:
        raise ValueError("source does not parse")
    return tree, data


def walk(node: Node) -> Iterator[Node]:
    yield node
    for c in node.children:
        yield from walk(c)


@dataclass(frozen=True)
class DefineSite:
    name: str
    value: int
    start: int  # byte span of the literal
    end: int


def defines(code: str) -> dict[str, DefineSite]:
    """`#define NAME <integer literal>` sites."""
    tree, data = parse(code)
    out: dict[str, DefineSite] = {}
    for n in walk(tree.root_node):
        if n.type != "preproc_def":
            continue
        name, value = n.child_by_field_name("name"), n.child_by_field_name("value")
        if name is None or value is None:
            continue
        raw = value.text.decode()
        text = raw.strip()
        try:
            v = int(text.rstrip("uUlL"), 0)
        except ValueError:
            continue
        start = value.start_byte + (len(raw) - len(raw.lstrip()))
        out[name.text.decode()] = DefineSite(name.text.decode(), v, start, start + len(text))
    return out


def replace_spans(data: bytes, edits: list[tuple[int, int, str]]) -> str:
    """Apply non-overlapping byte-span replacements. Overlaps are an error, never dropped."""
    edits = sorted(edits)
    for (s1, e1, _), (s2, _, _) in zip(edits, edits[1:]):
        if s2 < e1:
            raise ValueError(f"overlapping edits at bytes {s1}-{e1} and {s2}")
    out = data
    for s, e, r in reversed(edits):
        out = out[:s] + r.encode("utf-8") + out[e:]
    return out.decode("utf-8")


def set_parameters(code: str, values: dict[str, int]) -> str:
    """Return the program with the given #define parameters set to new values."""
    sites = defines(code)
    missing = set(values) - set(sites)
    if missing:
        raise KeyError(f"parameters not defined in program: {sorted(missing)}")
    _, data = parse(code)
    return replace_spans(data, [(sites[k].start, sites[k].end, str(v)) for k, v in values.items()])


def params_header(values: dict[str, int]) -> str:
    """Header through which harnesses see the candidate's parameter values (Post_theta)."""
    lines = ["/* generated by intentc: implementation parameters of the candidate */"]
    lines += [f"#define {k} {v}" for k, v in sorted(values.items())]
    return "\n".join(lines) + "\n"
